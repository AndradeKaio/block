#!/usr/bin/env python3
"""
codegen.py — Generate and compile a BLAS-calling C kernel from a block GEMM plan.

The generated block_spmm() function:
  - stores all GEMM parameters in static arrays (no switch/if forests)
  - multi-group  (n_groups > 1): #pragma omp parallel for over groups;
    groups have non-overlapping output regions so no write races
  - single-group (n_groups == 1): #pragma omp parallel for over contributions
    with per-thread accumulation buffers, then a sequential reduction

Usage as module:
    from codegen import generate_and_compile
    fn, compile_s = generate_and_compile(
        fused_contributions, fused_blocks, A_blocks, B_blocks,
        out_dir='.', dtype='float64')
    C_flat = fn(A_flat, B_flat)   # → np.ndarray

Usage as script (generates + prints C to stdout):
    python codegen.py              # uses a toy example
"""

import ctypes
import ctypes.util
import os
import subprocess
import time
from pathlib import Path
from typing import Callable, Optional, Tuple

import numpy as np


# ── C source generation ───────────────────────────────────────────────────────


def _arr(name: str, vals, ctype: str = "int", per_line: int = 12) -> str:
    """Emit a named C static array with line-wrapped values."""
    rows = []
    for i in range(0, len(vals), per_line):
        rows.append("    " + ", ".join(str(v) for v in vals[i : i + per_line]))
    return f"static const {ctype} {name}[] = {{\n" + ",\n".join(rows) + "\n};"


def generate_c(
    fused_contributions: dict,
    fused_blocks: list,
    A_blocks: list,
    B_blocks: list,
    dtype: str = "float64",
) -> str:
    """
    Return a C source string implementing:

        void block_spmm(const T* A_data, const T* B_data,
                              T* C_data, int C_size);

    where T = double (float64) or float (float32).

    A_data / B_data are the flat block arrays produced by generate_block_sparse_matrix.
    C_data is zero-initialised inside the function.
    """
    is_f64 = dtype == "float64"
    scalar = "double" if is_f64 else "float"
    gemm = "cblas_dgemm" if is_f64 else "cblas_sgemm"
    one = "1.0" if is_f64 else "1.0f"

    # ── Flatten contributions and record group boundaries ─────────────────────
    group_ids = list(fused_contributions.keys())
    group_starts = []  # group_starts[g]..group_starts[g+1]
    all_contribs = []  # (ai, bi, k_range, g_idx)
    for g_idx, gid in enumerate(group_ids):
        group_starts.append(len(all_contribs))
        for c in fused_contributions[gid]:
            all_contribs.append((c[0], c[1], c[2], g_idx))
    group_starts.append(len(all_contribs))  # sentinel

    n_groups = len(fused_blocks)
    n_contribs = len(all_contribs)

    # ── Precompute BLAS parameters for every contribution ─────────────────────
    M_v, N_v, K_v = [], [], []
    A_off_v, A_lda_v = [], []
    B_off_v, B_ldb_v = [], []
    C_goff_v, C_loff_v, C_ldc_v = [], [], []  # global / local / ldc

    for ai, bi, k_range, g_idx in all_contribs:
        lhs = A_blocks[ai]
        rhs = B_blocks[bi]
        out = fused_blocks[g_idx]

        k_len = k_range[1] - k_range[0] + 1
        ak0 = k_range[0] - lhs.c_start
        bk0 = k_range[0] - rhs.r_start
        or0 = lhs.r_start - out.r_start
        oc0 = rhs.c_start - out.c_start

        M_v.append(lhs.h)
        N_v.append(rhs.w)
        K_v.append(k_len)
        A_off_v.append(lhs.offset + ak0)
        A_lda_v.append(lhs.w)
        B_off_v.append(rhs.offset + bk0 * rhs.w)
        B_ldb_v.append(rhs.w)
        C_ldc_v.append(out.w)
        C_loff_v.append(or0 * out.w + oc0)  # local to output block
        C_goff_v.append(out.offset + or0 * out.w + oc0)  # global in C_flat

    # ── Build source ──────────────────────────────────────────────────────────
    L = []

    L += [
        "/* Auto-generated by codegen.py — do not edit */",
        "#include <stdlib.h>",
        "#include <string.h>",
        "#ifdef _OPENMP",
        "#include <omp.h>",
        "#else",
        "static int omp_get_max_threads(void) { return 1; }",
        "static int omp_get_thread_num(void)  { return 0; }",
        "#endif",
        "",
        "/* Inline CBLAS declarations — no cblas.h required on include path */",
        "void cblas_dgemm(int,int,int,int,int,int,double,"
        "const double*,int,const double*,int,double,double*,int);",
        "void cblas_sgemm(int,int,int,int,int,int,float,"
        "const float*,int,const float*,int,float,float*,int);",
        "",
    ]

    # Contribution parameter arrays
    L += [
        f"static const int NC = {n_contribs};",
        _arr("M_v", M_v),
        _arr("N_v", N_v),
        _arr("K_v", K_v),
        _arr("A_off", A_off_v, "long"),
        _arr("A_lda", A_lda_v),
        _arr("B_off", B_off_v, "long"),
        _arr("B_ldb", B_ldb_v),
        _arr("C_ldc", C_ldc_v),
        "",
    ]

    if n_groups > 1:
        # Global C offsets + group boundary arrays for multi-group path
        L += [
            _arr("C_goff", C_goff_v, "long"),
            f"static const int NG = {n_groups};",
            _arr("G_start", group_starts),
            "",
        ]
    else:
        # Local C offsets + output block metadata for single-group path
        out0 = fused_blocks[0]
        L += [
            _arr("C_loff", C_loff_v, "long"),
            f"static const long OUT_BASE = {out0.offset}L;",
            f"static const long OUT_SIZE = {out0.num_cells()}L;",
            "",
        ]

    # Function body
    L += [
        f"void block_spmm(const {scalar}* A_data,",
        f"                const {scalar}* B_data,",
        f"                      {scalar}* C_data, int C_size) {{",
        f"    memset(C_data, 0, (size_t)C_size * sizeof({scalar}));",
        "",
    ]

    if n_groups > 1:
        # ── Multi-group: parallel over groups ─────────────────────────────────
        # Each group writes to a distinct region of C_data → no races.
        L += [
            # "    #pragma omp parallel for schedule(dynamic)",
            "    for (int g = 0; g < NG; g++) {",
            "        for (int ci = G_start[g]; ci < G_start[g+1]; ci++) {",
            f"            {gemm}(101,111,111,",
            f"                M_v[ci],N_v[ci],K_v[ci],{one},",
            "                A_data+A_off[ci],A_lda[ci],",
            "                B_data+B_off[ci],B_ldb[ci],",
            f"                {one},C_data+C_goff[ci],C_ldc[ci]);",
            "        }",
            "    }",
        ]
    else:
        # ── Single-group: parallel over contributions with thread buffers ──────
        # Multiple contributions may overlap in the output → per-thread accumulation.
        L += [
            f"    int nt = omp_get_max_threads();",
            f"    {scalar}* tbufs = ({scalar}*)calloc((size_t)nt * OUT_SIZE, sizeof({scalar}));",
            # "    #pragma omp parallel for schedule(dynamic)",
            "    for (int ci = 0; ci < NC; ci++) {",
            "        int tid = omp_get_thread_num();",
            f"        {scalar}* tb = tbufs + (size_t)tid * OUT_SIZE;",
            f"        {gemm}(101,111,111,",
            f"            M_v[ci],N_v[ci],K_v[ci],{one},",
            "            A_data+A_off[ci],A_lda[ci],",
            "            B_data+B_off[ci],B_ldb[ci],",
            f"            {one},tb+C_loff[ci],C_ldc[ci]);",
            "    }",
            f"    /* reduce {n_groups == 1 and 'n_threads' or ''} buffers into output */",
            f"    {scalar}* C_out = C_data + OUT_BASE;",
            "    for (int t = 0; t < nt; t++) {",
            f"        {scalar}* tb = tbufs + (size_t)t * OUT_SIZE;",
            "        for (long i = 0; i < OUT_SIZE; i++) C_out[i] += tb[i];",
            "    }",
            "    free(tbufs);",
        ]

    L += ["}", ""]
    return "\n".join(L)


# ── Compilation ───────────────────────────────────────────────────────────────


def _blas_link_flags() -> list:
    """Return linker flags for the available BLAS library."""
    for name in ("openblas", "blas"):
        if ctypes.util.find_library(name):
            return [f"-l{name}"]
    return ["-lopenblas"]  # fallback: let the user fix the path


def compile_shared_lib(
    c_src: str,
    out_dir: str = ".",
    label: str = "gemm_plan",
) -> Optional[str]:
    """
    Write c_src to <out_dir>/<label>.c, compile to <out_dir>/lib<label>.so.
    Returns the .so path on success, None on failure.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    c_path = str(out / f"{label}.c")
    so_path = str(out.resolve() / f"lib{label}.so")

    with open(c_path, "w") as f:
        f.write(c_src)

    cmd = (
        [
            "gcc",
            "-O3",
            "-march=native",
            "-fopenmp",
            "-shared",
            "-fPIC",
            "-o",
            so_path,
            c_path,
        ]
        + _blas_link_flags()
        + ["-lm"]
    )

    print(f"  Compiling codegen kernel: {' '.join(cmd)}")
    try:
        subprocess.run(cmd, check=True, capture_output=True)
    except subprocess.CalledProcessError as e:
        print(f"  Compile failed:\n{e.stderr.decode().strip()}")
        return None
    return so_path


def make_callable(
    so_path: str,
    total_C_size: int,
    dtype,
) -> Callable:
    """
    Load the compiled shared library and return a Python callable:
        fn(A_flat, B_flat) → C_flat  (np.ndarray)
    """
    lib = ctypes.CDLL(so_path)
    is_f64 = np.dtype(dtype) == np.float64
    scalar_t = ctypes.c_double if is_f64 else ctypes.c_float
    lib.block_spmm.restype = None
    lib.block_spmm.argtypes = [
        ctypes.c_void_p,  # A_data
        ctypes.c_void_p,  # B_data
        ctypes.c_void_p,  # C_data
        ctypes.c_int,  # C_size
    ]

    def call(A_flat: np.ndarray, B_flat: np.ndarray) -> np.ndarray:
        C_flat = np.empty(total_C_size, dtype=dtype)
        lib.block_spmm(
            A_flat.ctypes.data,
            B_flat.ctypes.data,
            C_flat.ctypes.data,
            ctypes.c_int(total_C_size),
        )
        return C_flat

    return call


# ── Public entry point ────────────────────────────────────────────────────────


def generate_and_compile(
    fused_contributions: dict,
    fused_blocks: list,
    A_blocks: list,
    B_blocks: list,
    out_dir: str = ".",
    dtype="float64",
) -> Tuple[Optional[Callable], float]:
    """
    Generate C, compile to a shared library, return (callable, compile_time_s).
    The callable has signature:  fn(A_flat, B_flat) → C_flat (np.ndarray).
    Returns (None, compile_time_s) if compilation fails.

    fused_blocks must have .offset already assigned (call assign_offsets first).
    """
    dtype_str = np.dtype(dtype).name
    total_C_size = sum(b.num_cells() for b in fused_blocks)

    t0 = time.perf_counter()
    c_src = generate_c(fused_contributions, fused_blocks, A_blocks, B_blocks, dtype_str)
    so = compile_shared_lib(c_src, out_dir)
    compile_s = time.perf_counter() - t0

    if so is None:
        return None, compile_s

    fn = make_callable(so, total_C_size, dtype)
    return fn, compile_s


# ── Helpers used by the benchmark ─────────────────────────────────────────────


def assign_offsets(fused_blocks: list) -> int:
    """
    Set .offset on each fused block (row-major, contiguous).
    Returns total number of elements across all blocks.
    """
    off = 0
    for b in fused_blocks:
        b.offset = off
        off += b.num_cells()
    return off


# ── Scalar loop code generation ───────────────────────────────────────────────


def generate_c_loops(
    fused_contributions: dict,
    fused_blocks: list,
    A_blocks: list,
    B_blocks: list,
    dtype: str = "float64",
) -> str:
    """
    Generate a C source file implementing block_spmm() using plain i-k-j loops
    instead of BLAS calls.

    Loop order i→k→j (row-stationary):
      - outer i: iterates over rows of the output tile
      - middle k: broadcasts a_val = A[i,k] and does a SAXPY into c_row
      - inner j: c_row[j] += a_val * b_row[j]   ← auto-vectorised by gcc -O3

    With -O3 -march=native -ffast-math GCC/Clang vectorise the j-loop into
    AVX2/AVX-512 FMA instructions. No packing → worse cache reuse than BLAS for
    large tiles, but zero call overhead → wins for small tiles (< ~32×32).

    Parallelism mirrors generate_c:
      - multi-group : #pragma omp parallel for over groups (no races)
      - single-group: parallel over contributions + per-thread buffers + reduce
    """
    is_f64 = dtype == "float64"
    scalar = "double" if is_f64 else "float"

    # ── Flatten contributions ─────────────────────────────────────────────────
    group_ids = list(fused_contributions.keys())
    group_starts = []
    all_contribs = []
    for g_idx, gid in enumerate(group_ids):
        group_starts.append(len(all_contribs))
        for c in fused_contributions[gid]:
            all_contribs.append((c[0], c[1], c[2], g_idx))
    group_starts.append(len(all_contribs))

    n_groups = len(fused_blocks)
    n_contribs = len(all_contribs)

    # ── GEMM parameters (same layout as generate_c) ──────────────────────────
    M_v, N_v, K_v = [], [], []
    A_off_v, A_lda_v = [], []
    B_off_v, B_ldb_v = [], []
    C_goff_v, C_loff_v, C_ldc_v = [], [], []

    for ai, bi, k_range, g_idx in all_contribs:
        lhs = A_blocks[ai]
        rhs = B_blocks[bi]
        out = fused_blocks[g_idx]
        k_len = k_range[1] - k_range[0] + 1
        ak0 = k_range[0] - lhs.c_start
        bk0 = k_range[0] - rhs.r_start
        or0 = lhs.r_start - out.r_start
        oc0 = rhs.c_start - out.c_start

        M_v.append(lhs.h)
        N_v.append(rhs.w)
        K_v.append(k_len)
        A_off_v.append(lhs.offset + ak0)
        A_lda_v.append(lhs.w)
        B_off_v.append(rhs.offset + bk0 * rhs.w)
        B_ldb_v.append(rhs.w)
        C_ldc_v.append(out.w)
        C_loff_v.append(or0 * out.w + oc0)
        C_goff_v.append(out.offset + or0 * out.w + oc0)

    # ── Build source ──────────────────────────────────────────────────────────
    L = []

    L += [
        "/* Auto-generated by codegen.py (scalar loops) — do not edit */",
        "#include <stdlib.h>",
        "#include <string.h>",
        "#ifdef _OPENMP",
        "#include <omp.h>",
        "#else",
        "static int omp_get_max_threads(void) { return 1; }",
        "static int omp_get_thread_num(void)  { return 0; }",
        "#endif",
        "",
    ]

    # Parameter arrays
    L += [
        f"static const int NC = {n_contribs};",
        _arr("M_v", M_v),
        _arr("N_v", N_v),
        _arr("K_v", K_v),
        _arr("A_off", A_off_v, "long"),
        _arr("A_lda", A_lda_v),
        _arr("B_off", B_off_v, "long"),
        _arr("B_ldb", B_ldb_v),
        _arr("C_ldc", C_ldc_v),
        "",
    ]

    if n_groups > 1:
        L += [
            _arr("C_goff", C_goff_v, "long"),
            f"static const int NG = {n_groups};",
            _arr("G_start", group_starts),
            "",
        ]
    else:
        out0 = fused_blocks[0]
        L += [
            _arr("C_loff", C_loff_v, "long"),
            f"static const long OUT_BASE = {out0.offset}L;",
            f"static const long OUT_SIZE = {out0.num_cells()}L;",
            "",
        ]

    # Inner loop macro: i-k-j with restrict + omp simd
    # c_ptr: pointer to C output row  (double* restrict)
    # a_ptr: pointer to A slice row   (const double* restrict, offset by ak0)
    # b_base: pointer to B block row 0 (const double* restrict, offset by bk0*ldb)
    def loop_body(c_ptr_expr, a_off_expr, b_off_expr, ci_var="ci"):
        return [
            f"        {{",
            f"            int _M=M_v[{ci_var}], _N=N_v[{ci_var}], _K=K_v[{ci_var}];",
            f"            int _alda=A_lda[{ci_var}], _bldb=B_ldb[{ci_var}], _cldc=C_ldc[{ci_var}];",
            f"            long _aoff={a_off_expr}, _boff={b_off_expr};",
            f"            for (int _i=0; _i<_M; _i++) {{",
            f"                const {scalar}* restrict _ar = A_data+_aoff+(long)_i*_alda;",
            f"                {scalar}* restrict _cr = {c_ptr_expr}+(long)_i*_cldc;",
            f"                for (int _p=0; _p<_K; _p++) {{",
            f"                    {scalar} _av = _ar[_p];",
            f"                    const {scalar}* restrict _br = B_data+_boff+(long)_p*_bldb;",
            f"                    #pragma omp simd",
            f"                    for (int _j=0; _j<_N; _j++)",
            f"                        _cr[_j] += _av * _br[_j];",
            f"                }}",
            f"            }}",
            f"        }}",
        ]

    # Function signature
    L += [
        f"void block_spmm(const {scalar}* A_data,",
        f"                const {scalar}* B_data,",
        f"                      {scalar}* C_data, int C_size) {{",
        f"    memset(C_data, 0, (size_t)C_size * sizeof({scalar}));",
        "",
    ]

    if n_groups > 1:
        # Parallel over groups, sequential triple loop per contribution
        L += [
            # "    #pragma omp parallel for schedule(dynamic)",
            "    for (int g = 0; g < NG; g++) {",
            "        for (int ci = G_start[g]; ci < G_start[g+1]; ci++) {",
        ]
        L += [
            l.replace("        ", "            ")
            for l in loop_body("C_data+C_goff[ci]", "A_off[ci]", "B_off[ci]")
        ]
        L += ["        }", "    }"]
    else:
        # Single group: parallel over contributions, per-thread buffers
        L += [
            "    int nt = omp_get_max_threads();",
            f"    {scalar}* tbufs = ({scalar}*)calloc((size_t)nt*OUT_SIZE, sizeof({scalar}));",
            # "    #pragma omp parallel for schedule(dynamic)",
            "    for (int ci = 0; ci < NC; ci++) {",
            "        int tid = omp_get_thread_num();",
            f"        {scalar}* tb = tbufs + (size_t)tid * OUT_SIZE;",
        ]
        L += loop_body("tb+C_loff[ci]", "A_off[ci]", "B_off[ci]")
        L += [
            "    }",
            f"    {scalar}* C_out = C_data + OUT_BASE;",
            "    for (int t = 0; t < nt; t++) {",
            f"        {scalar}* tb = tbufs + (size_t)t * OUT_SIZE;",
            "        for (long i = 0; i < OUT_SIZE; i++) C_out[i] += tb[i];",
            "    }",
            "    free(tbufs);",
        ]

    L += ["}", ""]
    return "\n".join(L)


def generate_and_compile_loops(
    fused_contributions: dict,
    fused_blocks: list,
    A_blocks: list,
    B_blocks: list,
    out_dir: str = ".",
    dtype="float64",
) -> Tuple[Optional[Callable], float]:
    """
    Generate scalar loop C, compile with -ffast-math for auto-vectorisation.
    Returns (callable, compile_time_s).  callable: fn(A_flat, B_flat) → C_flat.
    """
    dtype_str = np.dtype(dtype).name
    total_C_size = sum(b.num_cells() for b in fused_blocks)

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    c_path = str(out / "gemm_plan_loops.c")
    so_path = str(out.resolve() / "libgemm_plan_loops.so")

    t0 = time.perf_counter()
    c_src = generate_c_loops(
        fused_contributions, fused_blocks, A_blocks, B_blocks, dtype_str
    )
    with open(c_path, "w") as f:
        f.write(c_src)

    # -ffast-math: enables reassociation + fused FMA, critical for the
    # auto-vectoriser to emit efficient SAXPY code in the inner j-loop.
    cmd = [
        "gcc",
        "-O3",
        "-march=native",
        "-fopenmp",
        "-ffast-math",
        "-shared",
        "-fPIC",
        "-o",
        so_path,
        c_path,
        "-lm",
    ]
    print(f"  Compiling scalar loops kernel: {' '.join(cmd)}")
    try:
        subprocess.run(cmd, check=True, capture_output=True)
    except subprocess.CalledProcessError as e:
        print(f"  Compile failed:\n{e.stderr.decode().strip()}")
        return None, time.perf_counter() - t0

    compile_s = time.perf_counter() - t0
    fn = make_callable(so_path, total_C_size, dtype)
    return fn, compile_s


