// bench_taco_spmm_bcsr.cpp — SpMM benchmark: A = S * C using a TACO-generated
// BCSR (block-compressed-sparse-row) kernel, fixed uniform block size.
//
// Structurally separate from bench_taco_spmm.cpp (the plain-CSR contender):
// taco_kernel_bcsr.h's tensors have different rank (S is a 4-mode tensor
// (io,jo,ii,ji) with format dsdd; the CSR kernel's S is 2-mode (i,j) with
// format ds) and different pack_A/compute/assemble signatures, so sharing
// one harness file isn't practical -- this mirrors that project's own
// choice to keep taco_kernel.h/taco_kernel_opt_*.h interchangeable (same
// tensor rank/signatures, selected via #if/#elif in ONE bench file) while
// giving BCSR its own file.
//
// BCSR requires ONE FIXED block size (bh,bw) for the whole matrix -- taco's
// "dense" mode type means ii/ji are fixed-size dimensions shared by every
// block, unlike Prisma's per-block variable-shape mining. This harness does
// its OWN from-scratch .mtx -> BCSR conversion (independent of any .bsp
// mining) at a caller-chosen (bh,bw), via --block-size (square blocks) or
// --block-h/--block-w (rectangular). No re-tiling code is generated by
// taco itself; pack_A (in taco_kernel_bcsr.h) already zero-fills any block
// cell not present in the COO stream, so this harness only needs to emit
// COO quadruples (io,jo,ii,ji,val) for S's TRUE nonzeros, sorted
// lexicographically by (io,jo,ii,ji) -- NOT the same order read_mtx's
// (row,col) sort produces (that's (io,ii,jo,ji) order effectively; pack_A's
// segment-sweep algorithm requires io grouped first, then jo within io,
// then ii within (io,jo), then ji -- a real re-sort, not a reused one).
//
// Padding: if M isn't a multiple of bh (or N isn't a multiple of bw), the
// padded tail (rows M..io_dim*bh-1 of C; rows N..jo_dim*bw-1 of the dense
// operand D) is always zero and never corrupts the real M x N result --
// see this file's build_bcsr_coo()/main() comments for why. Dumped output
// only ever writes the true M*N prefix.
//
// CLI: bench_taco_spmm_bcsr <S.mtx> [--runs R] [--seed S]
//                           [--block-size B | --block-h H --block-w W]
//                           [--dump-c path]
//
// Output format matches bench_taco_spmm.cpp (run_N_assemble_ns=/
// run_N_compute_ns=/... lines), same Python parser applies, plus
// block_h=/block_w=/io_dim=/jo_dim= for diagnostics.
//
// Compile:
//   g++ -O3 -std=c++17 -fopenmp -march=native -Drestrict=__restrict__ -I. \
//       bench_taco_spmm_bcsr.cpp -lm -o bench_taco_spmm_bcsr

#include <algorithm>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <ctime>
#include <random>
#include <string>
#include <vector>

#include "taco_kernel_bcsr.h"

typedef struct { int row, col; double val; } entry_t;

static int entry_cmp(const void *a, const void *b) {
    const entry_t *ea = (const entry_t *)a, *eb = (const entry_t *)b;
    return ea->row != eb->row ? ea->row - eb->row : ea->col - eb->col;
}

// Identical to bench_taco_spmm.cpp's read_mtx (same MTX-parsing edge cases
// already fixed there: banner-only format/symmetry detection, complex
// rejection, symmetric mirroring) -- kept as a verbatim copy rather than a
// shared header so each bench stays a single self-contained translation
// unit, matching this project's existing bench_taco_spmm.c/.cpp precedent.
static int read_mtx(const char *path, int *M, int *N, int *nnz,
                    int **rows, int **cols, double **vals) {
    FILE *f = fopen(path, "r");
    if (!f) { fprintf(stderr, "cannot open %s\n", path); return -1; }
    char line[512];

    if (!fgets(line, sizeof(line), f)) { fclose(f); return -1; }
    char banner[512];
    std::strncpy(banner, line, sizeof(banner));
    banner[sizeof(banner) - 1] = '\0';
    for (char *p = banner; *p; ++p) *p = (char)tolower((unsigned char)*p);
    int is_pattern   = strstr(banner, "pattern") != nullptr;
    int is_symmetric = strstr(banner, "symmetric") || strstr(banner, "hermitian");
    if (strstr(banner, "complex")) {
        fprintf(stderr, "read_mtx: complex-valued matrices are not supported: %s\n", path);
        fclose(f);
        return -1;
    }

    while (fgets(line, sizeof(line), f)) {
        if (line[0] != '%') break;
    }
    if (sscanf(line, "%d %d %d", M, N, nnz) != 3) { fclose(f); return -1; }

    int cap = is_symmetric ? *nnz * 2 : *nnz;
    entry_t *e = (entry_t *)malloc((size_t)cap * sizeof(entry_t));
    int n = 0;
    for (int i = 0; i < *nnz; i++) {
        int r, c; double v = 1.0;
        if (is_pattern) {
            if (fscanf(f, "%d %d",      &r, &c)     < 2) continue;
        } else {
            if (fscanf(f, "%d %d %lf", &r, &c, &v) < 2) continue;
        }
        --r; --c;
        e[n++] = {r, c, v};
        if (is_symmetric && r != c)
            e[n++] = {c, r, v};
    }
    fclose(f);
    qsort(e, n, sizeof(entry_t), entry_cmp);
    *nnz  = n;
    *rows = (int *)   malloc((size_t)n * sizeof(int));
    *cols = (int *)   malloc((size_t)n * sizeof(int));
    *vals = (double *)malloc((size_t)n * sizeof(double));
    for (int i = 0; i < n; i++) {
        (*rows)[i] = e[i].row;
        (*cols)[i] = e[i].col;
        (*vals)[i] = e[i].val;
    }
    free(e);
    return 0;
}

static taco_tensor_t *make_bcsr(int io_dim, int jo_dim, int bh, int bw) {
    int32_t dims[4] = {io_dim, jo_dim, bh, bw}, ord[4] = {0, 1, 2, 3};
    taco_mode_t modes[4] = {taco_mode_dense, taco_mode_sparse,
                            taco_mode_dense, taco_mode_dense};
    taco_tensor_t *t = init_taco_tensor_t(4, sizeof(double), dims, ord, modes);
    t->indices[1][0] = t->indices[1][1] = t->vals = NULL;
    t->fill_value = NULL;
    t->vals_size = 0;
    return t;
}

static taco_tensor_t *make_dense3(int d0, int d1, int d2) {
    int32_t dims[3] = {d0, d1, d2}, ord[3] = {0, 1, 2};
    taco_mode_t modes[3] = {taco_mode_dense, taco_mode_dense, taco_mode_dense};
    taco_tensor_t *t = init_taco_tensor_t(3, sizeof(double), dims, ord, modes);
    t->vals = NULL;
    t->fill_value = NULL;
    t->vals_size = 0;
    return t;
}

static void reset_output(taco_tensor_t *A) {
    if (A->vals) { free(A->vals); A->vals = NULL; }
}

static long ns_now(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (long)ts.tv_sec * 1000000000L + ts.tv_nsec;
}

// Converts S's true nonzeros (already read into row-sorted rows/cols/vals)
// into the four COO coordinate arrays pack_A expects, in (io,jo,ii,ji)
// lexicographic order -- NOT the (row,col) order read_mtx produced (see
// this file's header comment for why those differ). Returns nnz (== input
// nnz; BCSR block conversion doesn't change nonzero count, only groups them
// into dense blocks).
static int build_bcsr_coo(int nnz, const int *rows, const int *cols,
                          const double *vals, int bh, int bw,
                          std::vector<int> &io_a, std::vector<int> &jo_a,
                          std::vector<int> &ii_a, std::vector<int> &ji_a,
                          std::vector<double> &val_a) {
    io_a.resize(nnz); jo_a.resize(nnz); ii_a.resize(nnz); ji_a.resize(nnz);
    val_a.resize(nnz);
    std::vector<int> order(nnz);
    for (int i = 0; i < nnz; i++) order[i] = i;

    // Precompute block coords once so the sort comparator is cheap.
    std::vector<int> io_of(nnz), jo_of(nnz), ii_of(nnz), ji_of(nnz);
    for (int i = 0; i < nnz; i++) {
        io_of[i] = rows[i] / bh;
        ii_of[i] = rows[i] % bh;
        jo_of[i] = cols[i] / bw;
        ji_of[i] = cols[i] % bw;
    }
    std::sort(order.begin(), order.end(), [&](int a, int b) {
        if (io_of[a] != io_of[b]) return io_of[a] < io_of[b];
        if (jo_of[a] != jo_of[b]) return jo_of[a] < jo_of[b];
        if (ii_of[a] != ii_of[b]) return ii_of[a] < ii_of[b];
        return ji_of[a] < ji_of[b];
    });
    for (int i = 0; i < nnz; i++) {
        int j = order[i];
        io_a[i] = io_of[j]; jo_a[i] = jo_of[j];
        ii_a[i] = ii_of[j]; ji_a[i] = ji_of[j];
        val_a[i] = vals[j];
    }
    return nnz;
}

int main(int argc, char *argv[]) {
    if (argc < 2) {
        fprintf(stderr,
               "usage: %s S.mtx [--runs R] [--seed S] "
               "[--block-size B | --block-h H --block-w W] [--dump-c path]\n",
               argv[0]);
        return 1;
    }
    const char *mtx_path = argv[1];
    int n_runs = 5;
    int seed   = 42;
    int bh = 6, bw = 6; // default: matches the mode block shape common
                        // across this project's mined-block corpus (see
                        // suite-sparse/benchmark_spmm.py's shape analysis);
                        // always override via --block-size for a real sweep.
    const char *dump_c_path = nullptr;

    for (int i = 2; i < argc; i++) {
        if (strcmp(argv[i], "--runs") == 0 && i + 1 < argc)
            n_runs = atoi(argv[++i]);
        else if (strcmp(argv[i], "--seed") == 0 && i + 1 < argc)
            seed = atoi(argv[++i]);
        else if (strcmp(argv[i], "--block-size") == 0 && i + 1 < argc)
            bh = bw = atoi(argv[++i]);
        else if (strcmp(argv[i], "--block-h") == 0 && i + 1 < argc)
            bh = atoi(argv[++i]);
        else if (strcmp(argv[i], "--block-w") == 0 && i + 1 < argc)
            bw = atoi(argv[++i]);
        else if (strcmp(argv[i], "--dump-c") == 0 && i + 1 < argc)
            dump_c_path = argv[++i];
    }
    if (bh <= 0 || bw <= 0) {
        fprintf(stderr, "block-h/block-w must be positive\n");
        return 1;
    }

    int M, N, S_nnz;
    int *Sr, *Sc;
    double *Sv;
    long t_read0 = ns_now();
    if (read_mtx(mtx_path, &M, &N, &S_nnz, &Sr, &Sc, &Sv) != 0) return 1;
    long mtx_read_ns = ns_now() - t_read0;

    int K = N; // square dense operand, same convention as bench_taco_spmm.cpp

    const int io_dim = (M + bh - 1) / bh;
    const int jo_dim = (N + bw - 1) / bw;
    const int M_pad = io_dim * bh;
    const int N_pad = jo_dim * bw; // padded contraction-dim extent

    // ---- Build A (S) as BCSR ------------------------------------------
    std::vector<int> io_a, jo_a, ii_a, ji_a;
    std::vector<double> val_a;
    long t_bcsr0 = ns_now();
    build_bcsr_coo(S_nnz, Sr, Sc, Sv, bh, bw, io_a, jo_a, ii_a, ji_a, val_a);
    long bcsr_convert_ns = ns_now() - t_bcsr0;

    taco_tensor_t *A_t = make_bcsr(io_dim, jo_dim, bh, bw);
    int A_COO1_pos[2] = {0, S_nnz};
    long t_pack0 = ns_now();
    pack_A(A_t, A_COO1_pos, io_a.data(), jo_a.data(), ii_a.data(), ji_a.data(),
          val_a.data());
    long pack_a_ns = ns_now() - t_pack0;

    fprintf(stderr,
           "structural_setup: mtx_read=%.4fms  bcsr_convert=%.4fms  "
           "pack_a=%.4fms  block=%dx%d  io_dim=%d  jo_dim=%d  pad=%dx%d\n",
           mtx_read_ns / 1e6, bcsr_convert_ns / 1e6, pack_a_ns / 1e6, bh, bw,
           io_dim, jo_dim, M_pad, N_pad);

    // ---- Dense operand D, reshaped to B(jo,ji,k) -----------------------
    // Drawn with EXACTLY N*N values from the SAME mt19937_64 sequence every
    // other contender (CPU, GPU, plain-CSR TACO) uses -- correctness-
    // critical for validate_spmm.py's shared-D cross-comparison. Padding
    // rows (N..N_pad-1) are NOT extra rng draws (that would desync the
    // sequence from every other contender); they're deterministic zeros,
    // safe because A's ji range for the boundary block only has nonzero
    // A_vals for the TRUE columns < N (pack_A never set anything for the
    // padding sub-range), so padding rows only ever get multiplied by 0.
    std::vector<double> b_vals((size_t)N_pad * K, 0.0);
    {
        std::mt19937_64 rng((uint64_t)seed);
        std::uniform_real_distribution<double> dist(-1.0, 1.0);
        for (long long i = 0; i < (long long)N * K; i++)
            b_vals[i] = dist(rng); // rows 0..N-1 exactly, row-major -- same
                                   // layout as D's natural N x K, since
                                   // row = jo*bw+ji reconstructs the
                                   // original row index for jo*bw+ji < N.
    }
    taco_tensor_t *B_t = make_dense3(jo_dim, bw, K);
    B_t->vals = (uint8_t *)b_vals.data(); // direct assign, no pack_B needed
                                          // for a fully dense tensor -- same
                                          // shortcut bench_taco_spmm.cpp
                                          // uses for its dense operand.

    taco_tensor_t *C_t = make_dense3(io_dim, bh, K);

    long a_total = 0, c_total = 0;

    for (int r = 0; r <= n_runs; r++) {
        reset_output(C_t);
        long t0 = ns_now();
        assemble(C_t, A_t, B_t);
        long t1 = ns_now();
        compute(C_t, A_t, B_t);
        long t2 = ns_now();
        long a = t1 - t0, c = t2 - t1;
        if (r > 0) { a_total += a; c_total += c; }
        printf("run_%d_assemble_ns=%ld\n", r, a);
        printf("run_%d_compute_ns=%ld\n",  r, c);
        fflush(stdout);
    }

    // Dump output: C_vals is row-major (io*bh+ii, k) with ldc=K -- rows
    // 0..M-1 are exactly the true M x N result, CONTIGUOUS (padding rows
    // M..M_pad-1 only ever appear as a trailing tail, never interleaved),
    // so the first M*K elements are the plain M x N row-major array every
    // other contender's --dump-c already produces. No reshape needed.
    if (dump_c_path) {
        FILE *fout = fopen(dump_c_path, "wb");
        if (!fout) {
            fprintf(stderr, "bench_taco_spmm_bcsr: cannot open dump-c path: %s\n",
                   dump_c_path);
        } else {
            fwrite((double *)C_t->vals, sizeof(double), (size_t)M * K, fout);
            fclose(fout);
        }
    }

    printf("mean_assemble_ns=%ld\n", a_total / n_runs);
    printf("mean_compute_ns=%ld\n",  c_total / n_runs);
    printf("mtx_read_ns=%ld\n",      mtx_read_ns);
    printf("bcsr_convert_ns=%ld\n",  bcsr_convert_ns);
    printf("pack_a_ns=%ld\n",        pack_a_ns);
    printf("block_h=%d\n",           bh);
    printf("block_w=%d\n",           bw);
    printf("io_dim=%d\n",            io_dim);
    printf("jo_dim=%d\n",            jo_dim);
    printf("S_nnz=%d\n",    S_nnz);
    printf("S_rows=%d\n",   M);
    printf("S_cols=%d\n",   N);
    printf("num_vecs=%d\n", K);

    free(Sr); free(Sc); free(Sv);
    reset_output(C_t);
    deinit_taco_tensor_t(C_t);
    if (A_t->indices[1][0]) free(A_t->indices[1][0]);
    if (A_t->indices[1][1]) free(A_t->indices[1][1]);
    if (A_t->vals)          free(A_t->vals);
    deinit_taco_tensor_t(A_t);
    deinit_taco_tensor_t(B_t); // B_t->vals points into b_vals (a std::vector,
                               // freed automatically) -- do NOT free it here.
    return 0;
}
