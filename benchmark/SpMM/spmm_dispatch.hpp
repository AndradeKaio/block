#pragma once

// spmm_dispatch.hpp — specialized SpMM micro-kernels for fixed block shapes.
//
// For SpMM (C += A * B) where A is a small block (H×W), B is a wide dense
// matrix (W×N, N large and runtime), and C is the output (H×N).
//
// Strategy: fix H, W, and NR (column chunk width) at compile time so every
// loop inside a chunk-processing call is fully unrolled. The j-loop over N
// lives in spmm_kernel below, which processes NR-column slices and handles
// the tail.
//
// The per-chunk kernel itself is benchmark_core::cpu_detail::gemm_fixed
// (core/gen_kernel.py), shared with SpGEMM and SpMV -- this file used to
// carry its own separate spmm_chunk<H,W,NR> template (with its own
// AVX-512/AVX2/scalar bodies) doing the exact same thing; that's now one
// shared implementation instead of three. gemm_fixed's row-tiling handles
// the register-budget difference between ISAs at the SAME N automatically,
// so (unlike the old spmm_chunk-based scheme) there's no need to pick a
// smaller NR specifically for AVX2 -- one NR per shape suffices.

#include "cpu_dispatch.hpp"  // for gemm_fixed, gemm_fallback

namespace spmm_detail {

// ---------------------------------------------------------------------------
// spmm_kernel<H, W, NR> — sweeps j in NR-column chunks, scalar tail.
// This is the per-shape entry point called by spmm_dispatch.
// ---------------------------------------------------------------------------

template <int H, int W, int NR>
inline void spmm_kernel(int N,
                        const double* __restrict__ A, int lda,
                        const double* __restrict__ B, int ldb,
                        double*       __restrict__ C, int ldc) {
    // Prefetch first B chunk: W separate row streams may exceed HW prefetch
    // stream capacity, so cover them explicitly.
    // __builtin_prefetch is a portable GCC/Clang built-in (x86 PREFETCHT1 or
    // ARM PRFM PLDL2KEEP); no header required, locality=2 targets L2.
    for (int p = 0; p < W; ++p)
        __builtin_prefetch(B + p * ldb, 0, 2);

    int j = 0;
    for (; j + NR <= N; j += NR) {
        // Prefetch next B chunk into L2 while computing the current one.
        // Each row of B is ldb doubles away from the previous, which can
        // exceed the HW prefetcher's stream tracking on high-W shapes.
        if (j + NR < N) {
            for (int p = 0; p < W; ++p)
                __builtin_prefetch(B + j + NR + p * ldb, 0, 2);
        }
        benchmark_core::cpu_detail::gemm_fixed<H, W, NR, double>(A, lda, B + j, ldb, C + j, ldc);
    }

    // Hoist A into registers once for the tail (A is tiny, guaranteed in L1).
    double a_reg[H][W];
    for (int i = 0; i < H; ++i)
        for (int p = 0; p < W; ++p)
            a_reg[i][p] = A[i * lda + p];

    // Vectorised tail: handle remaining 8-column chunks via gemm_fallback
    // (#pragma omp simd on its inner loop) -- the same fallback SpGEMM and
    // SpMV use for anything unspecialized, rather than a bespoke tail-only
    // kernel. Always better than the unguarded scalar residue loop below.
    for (; j + 8 <= N; j += 8)
        benchmark_core::cpu_detail::gemm_fallback(H, W, 8, A, lda, B + j, ldb, C + j, ldc);

    // Scalar residue for the final < 8 columns.
    // Loop order: outer (i,p) so the inner j-stride over B[p*ldb+jj] is 1
    // (sequential), not stride-N per j as the naive j-outer ordering would give.
    if (j < N) {
        for (int i = 0; i < H; ++i)
            for (int p = 0; p < W; ++p) {
                const double av = a_reg[i][p];
                for (int jj = j; jj < N; ++jj)
                    C[i * ldc + jj] += av * B[p * ldb + jj];
            }
    }
}

} // namespace spmm_detail

